import { expect, test, type Page } from '@playwright/test'

const attention = '2024-2026年Transformer在长序列建模与注意力机制方面有哪些基础性创新？'

async function fakeBackend(page: Page, submitted: unknown[]) {
  await page.route('**/health', route => route.fulfill({ json: { status: 'ok' } }))
  await page.route('**/api/research/history?*', route => route.fulfill({ json: [] }))
  await page.route('**/api/research/stream', route => {
    submitted.push(route.request().postDataJSON())
    return route.fulfill({ contentType: 'text/event-stream', body: 'data: {"event":"error","message":"测试任务结束","error_id":"motion-test-trace"}\n\n' })
  })
}

test('ASCII keys keep their accessible names and dimensions while resolving', async ({ page }) => {
  await page.clock.install()
  await page.goto('/?demo=1')
  const key = page.getByRole('button', { name: '设置', exact: true })
  const label = key.locator('.ascii-key-label')
  const before = (await key.boundingBox())!
  await key.hover()
  await expect(label).toHaveAttribute('data-phase', 'decoding')
  await expect(key).toHaveAccessibleName('设置')
  expect((await key.boundingBox())!.width).toBeCloseTo(before.width, 1)
  await expect(page.getByRole('textbox', { name: '研究问题' })).toHaveValue('')
  await page.clock.runFor(400)
  await expect(label).toHaveAttribute('data-phase', 'idle')
  await expect(label).toHaveText('设置')
})

test('homepage questions decode, hold and delete as hints without replacing input or starting research', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()) })
  await page.clock.install()
  await page.goto('/?demo=1')
  const input = page.getByRole('textbox', { name: '研究问题', exact: true })
  const hint = page.locator('.home-entry .prompt-animated-hint')
  const advanceToPhase = async (phase: string) => {
    for (let attempt = 0; attempt < 120; attempt++) {
      if (await hint.getAttribute('data-phase') === phase) return
      await page.clock.runFor(100)
    }
    throw new Error(`Homepage hint did not reach ${phase}`)
  }
  await expect(hint).toBeVisible()
  await expect(hint).toHaveAttribute('aria-hidden', 'true')
  await page.clock.runFor(500)
  await expect(hint.locator('.prompt-cipher-glyph')).toHaveText(/^[A-Z0-9#$%&*+\-/<>\[\]{}]$/)
  await advanceToPhase('holding')
  const firstQuestion = await hint.locator('.prompt-resolved-text').innerText()
  expect(firstQuestion).toBe('大语言模型如何辅助科研？')
  await page.clock.runFor(5000)
  await expect(hint).toHaveAttribute('data-phase', 'holding')
  await expect(hint.locator('.prompt-resolved-text')).toHaveText(firstQuestion)
  await advanceToPhase('deleting')
  const deletingText = await hint.locator('.prompt-resolved-text').innerText()
  expect(firstQuestion.startsWith(deletingText)).toBe(true)
  expect(deletingText.length).toBeLessThan(firstQuestion.length)
  await advanceToPhase('holding')
  await expect(hint).toContainText('检索增强方法有哪些局限？')
  await expect(input).toHaveValue('')
  await page.setViewportSize({ width: 320, height: 844 })
  expect(await hint.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await input.focus()
  await expect(hint).toHaveCount(0)
  await input.fill('保留这个真实输入')
  await page.getByRole('heading', { name: 'B1GONE 研究助手', exact: true }).click()
  await page.clock.runFor(20000)
  await expect(input).toHaveValue('保留这个真实输入')
  await expect(hint).toHaveCount(0)
  await input.fill('')
  await page.getByRole('heading', { name: 'B1GONE 研究助手', exact: true }).click()
  await advanceToPhase('holding')
  await page.screenshot({ path: '../tmp/b1gone-home-prompt-animation.png' })
  await page.getByRole('button', { name: '开始研究', exact: true }).click()
  await expect(page).toHaveURL('/research?demo=1')
  await expect(page.getByRole('heading', { name: '从一个问题开始。' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: '研究问题', exact: true })).toHaveValue('')
  expect(requests).toEqual([])
})

test('robot blinks, looks toward input and previews agent tools without changing the question', async ({ page }) => {
  await page.clock.install()
  await page.goto('/?demo=1')
  const eyes = page.locator('.home-mascot .home-eyes')
  let blinkObserved = false
  for (let step = 0; step < 300; step++) {
    await page.clock.runFor(50)
    if (await eyes.getAttribute('data-eye-state') === 'blink') { blinkObserved = true; break }
  }
  expect(blinkObserved).toBe(true)
  await page.clock.runFor(140)
  await expect(eyes).toHaveAttribute('data-eye-state', 'idle')
  const input = page.getByRole('textbox', { name: '研究问题' })
  await input.fill('保留我的研究问题')
  await expect(eyes).toHaveAttribute('data-eye-state', 'look-left')
  await page.getByRole('button', { name: /查看 analysis 职能/ }).hover()
  await expect(page.locator('.home-mascot .home-visor-tool')).toHaveAttribute('data-role', 'analysis')
  await page.getByRole('button', { name: /查看 writer 职能/ }).focus()
  const cursor = page.locator('.home-mascot .home-visor-tool > rect')
  await expect(cursor).toHaveAttribute('opacity', '1')
  await page.clock.runFor(550)
  await expect(cursor).toHaveAttribute('opacity', '0')
  await input.focus()
  await page.getByRole('heading', { name: 'B1GONE 研究助手' }).hover()
  await expect(page.locator('.home-mascot .home-visor-tool')).toHaveCount(0)
  await expect(eyes).toHaveAttribute('data-eye-state', 'look-left')
  await expect(input).toHaveValue('保留我的研究问题')
  await page.screenshot({ path: '../tmp/b1gone-home-eyes.png' })
})

test('subquestions expand and fill the actual input through mouse, keyboard and touch without submitting', async ({ page }) => {
  const requests: string[] = []
  page.on('request', request => { if (request.url().includes('/api/')) requests.push(request.url()) })
  await page.goto('/?demo=1')
  const ray = page.getByRole('button', { name: '填入研究子问题：' + attention, exact: true })
  await ray.hover()
  await expect(page.getByRole('tooltip')).toContainText('long-sequence modeling')
  await expect(page.locator('[data-question=attention]')).toHaveAttribute('data-selected', 'true')
  await page.screenshot({ path: '../tmp/b1gone-home-subquestion.png' })
  await ray.click()
  const input = page.getByRole('textbox', { name: '研究问题' })
  await expect(input).toHaveValue(attention)
  await expect(input).toBeFocused()
  await input.fill('')
  await ray.focus()
  await ray.press('Space')
  await expect(input).toHaveValue(attention)
  await page.setViewportSize({ width: 390, height: 844 })
  await input.fill('')
  await page.getByRole('button', { name: '填入研究子问题：' + attention, exact: true }).click()
  await expect(input).toHaveValue(attention)
  await expect(page).toHaveURL('/?demo=1')
  expect(requests).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('launch freezes the real question, prevents repeated submission and hands off once', async ({ page }) => {
  const submitted: unknown[] = []
  await fakeBackend(page, submitted)
  await page.clock.install({ time: new Date('2026-10-11T12:00:00Z') })
  await page.goto('/')
  // Real time between browser assertions must not consume this 360ms window.
  await page.clock.pauseAt(new Date('2026-10-11T14:00:00Z'))
  await page.getByRole('textbox', { name: '研究问题' }).fill('仅提交这条实际问题')
  await page.getByRole('button', { name: '开始研究', exact: true }).click()
  await expect(page.locator('.home-screen')).toHaveAttribute('data-launch-state', 'entering')
  await expect(page.getByRole('textbox', { name: '研究问题' })).toBeDisabled()
  await page.getByRole('form', { name: '开始新研究' }).dispatchEvent('submit')
  await page.getByRole('form', { name: '开始新研究' }).dispatchEvent('submit')
  expect(submitted).toEqual([])
  await page.clock.runFor(220)
  await expect(page.locator('.home-prompt-packet')).toContainText('仅提交这条实际问题')
  await expect(page.locator('[data-question=attention] polygon')).toHaveAttribute('points', '620,200 630,200 630,200')
  await page.clock.runFor(200)
  await expect(page).toHaveURL('/research')
  await expect(page.getByRole('alert')).toContainText('motion-test-trace')
  expect(submitted).toEqual([{ query: '仅提交这条实际问题', max_papers: 15 }])
  await expect(page.locator('.home-entry-line')).toHaveAttribute('aria-hidden', 'true')
  await page.clock.runFor(500)
  await expect(page.locator('.home-entry-line')).toHaveCount(0)
})

test('reduced motion retains functional controls and submits with no animation delay', async ({ page }) => {
  const submitted: unknown[] = []
  await fakeBackend(page, submitted)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.clock.install()
  await page.goto('/')
  await expect(page.locator('.home-entry .prompt-animated-hint')).toHaveCount(0)
  await page.getByRole('button', { name: '设置', exact: true }).hover()
  await expect(page.locator('.home-nav .ascii-key-label').last()).toHaveText('设置')
  await expect(page.locator('.home-nav .ascii-key-label').last()).toHaveAttribute('data-phase', 'idle')
  await page.clock.runFor(6700)
  await expect(page.locator('.home-mascot .home-eyes')).toHaveAttribute('data-eye-state', 'idle')
  await page.getByRole('textbox', { name: '研究问题' }).fill('减少动效下的实际问题')
  await page.getByRole('button', { name: '开始研究', exact: true }).click()
  await expect(page).toHaveURL('/research')
  await expect(page.getByRole('alert')).toContainText('motion-test-trace')
  await expect(page.locator('.home-entry-line')).toHaveCount(0)
  expect(submitted).toHaveLength(1)
})

test('leaving the homepage during its exit animation clears the pending start', async ({ page }) => {
  await page.clock.install()
  await page.goto('/research?demo=1')
  await page.getByRole('button', { name: '返回首页', exact: true }).click()
  await page.getByRole('textbox', { name: '研究问题' }).fill('离开页面就不应提交的问题')
  await page.getByRole('button', { name: '开始研究', exact: true }).click()
  await expect(page.locator('.home-screen')).toHaveAttribute('data-launch-state', 'entering')
  await page.goBack()
  await page.clock.runFor(1000)
  await expect(page).toHaveURL('/research?demo=1')
  await expect(page.locator('.desktop-sidebar .history-item').filter({ hasText: '离开页面就不应提交的问题' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '研究综述', exact: true })).toBeVisible()
})

test('opening a dialog pauses decorative timers and restores readable labels', async ({ page }) => {
  await page.clock.install()
  await page.goto('/?demo=1')
  await expect(page.locator('.home-entry .prompt-animated-hint')).toBeVisible()
  await page.getByRole('button', { name: '文档', exact: true }).hover()
  await page.getByRole('button', { name: '文档', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '使用文档' })).toBeVisible()
  await expect(page.locator('.home-screen')).toHaveAttribute('data-motion', 'paused')
  await expect(page.locator('.home-entry .prompt-animated-hint')).toHaveCount(0)
  await page.clock.runFor(6700)
  await expect(page.locator('.home-mascot .home-eyes')).toHaveAttribute('data-eye-state', 'idle')
  await expect(page.locator('.home-nav .ascii-key-label').first()).toHaveText('文档')
  await page.getByRole('button', { name: '关闭文档', exact: true }).click()
  await expect(page.locator('.home-screen')).toHaveAttribute('data-motion', 'enabled')
  await expect(page.locator('.home-entry .prompt-animated-hint')).toBeVisible()
})
