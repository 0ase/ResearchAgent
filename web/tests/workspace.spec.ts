  await page.screenshot({ path: '../tmp/b1gone-papers-mobile.png' })
  await page.keyboard.press('Escape')
  await expect(papers).not.toBeVisible()
  await expect(page.getByRole('button', { name: '研究文献 · 15' })).toBeFocused()
