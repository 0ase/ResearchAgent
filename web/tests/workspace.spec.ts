import { expect, test } from '@playwright/test'

test('agent characters keep their identities after completion and show accessible role details', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/?demo=1')
  await page.evaluate(() => document.fonts.ready)
  await page.getByRole('button', { name: '研究过程' }).click()
  await expect(page.getByRole('button', { name: '查看调度员职责：拆解研究问题，已完成', exact: true })).toBeVisible()
  const search = page.getByRole('button', { name: '查看检索员职责：搜索相关文献，已完成', exact: true })
  await expect(search).toBeVisible()
  await page.screenshot({ path: '../tmp/b1gone-agent-timeline.png' })
  await search.click()
  const role = page.getByRole('dialog', { name: '检索员', exact: true })
  await expect(role).toBeVisible()
  await expect(role).toContainText('放大镜')
  await expect(role).toContainText('候选论文、检索来源与数量')
  await expect(role.locator('.agent-live-status')).toHaveText('已完成')
  await page.screenshot({ path: '../tmp/b1gone-agent-profile.png' })
  await page.keyboard.press('Escape')
  await expect(role).not.toBeVisible()
  await expect(search).toBeFocused()
  await page.setViewportSize({ width: 390, height: 844 })
  const mobilePapers = page.getByRole('dialog', { name: '研究文献', exact: true })
  if (await mobilePapers.isVisible()) await page.getByRole('button', { name: '关闭研究文献', exact: true }).click()
  await page.getByRole('button', { name: '查看阅读员职责：阅读与提取证据，已完成', exact: true }).click()
  const reader = page.getByRole('dialog', { name: '阅读员', exact: true })
  await expect(reader).toBeVisible()
  expect((await reader.boundingBox())!.width).toBeLessThanOrEqual(390)
  await page.getByRole('button', { name: '返回研究过程', exact: true }).click()
  expect(errors).toEqual([])
})

test('sidebar collapse preserves input and paper resizing survives reopening and smaller windows', async ({ page }) => {
  await page.goto('/?demo=1')
  const workspace = page.locator('.workspace')
  const papers = page.locator('.paper-panel')
  const before = await workspace.boundingBox()
  await page.getByRole('textbox', { name: '研究问题' }).fill('保留这条尚未提交的问题')
  await page.getByRole('button', { name: '收起侧边栏', exact: true }).click()
  await expect(page.getByRole('button', { name: '展开侧边栏', exact: true })).toBeFocused()
  expect((await workspace.boundingBox())!.width).toBeGreaterThan(before!.width + 150)
  await page.getByRole('button', { name: '展开侧边栏', exact: true }).click()
  await expect(page.getByRole('button', { name: '收起侧边栏', exact: true })).toBeFocused()
  await expect(page.getByRole('textbox', { name: '研究问题' })).toHaveValue('保留这条尚未提交的问题')
  await expect(page.getByRole('heading', { name: '研究综述', exact: true })).toBeVisible()

  const original = (await papers.boundingBox())!
  const separator = page.getByRole('separator', { name: '调整研究文献栏宽度' })
  const grip = (await separator.boundingBox())!
  await page.mouse.move(grip.x + grip.width / 2, 220)
  await page.mouse.down()
  await page.mouse.move(grip.x + grip.width / 2 - 180, 220, { steps: 12 })
  await page.mouse.up()
  await expect.poll(async () => (await papers.boundingBox())!.width).toBeGreaterThan(original.width + 170)
  const resizedWidth = (await papers.boundingBox())!.width
  await page.screenshot({ path: '../tmp/b1gone-resizable-sidebar.png' })
  await page.getByRole('button', { name: '关闭研究文献' }).click()
  await page.getByRole('button', { name: '研究文献 · 15' }).click()
  expect((await papers.boundingBox())!.width).toBeCloseTo(resizedWidth, 0)
  await separator.press('ArrowLeft')
  expect((await papers.boundingBox())!.width).toBeCloseTo(resizedWidth + 16, 0)
  await separator.press('Home')
  expect((await papers.boundingBox())!.width).toBe(260)
  await separator.press('End')
  await page.setViewportSize({ width: 1100, height: 800 })
  await expect.poll(async () => (await workspace.boundingBox())!.width).toBeGreaterThanOrEqual(419)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('completed report, citations, abstracts and export work without a backend', async ({ page }) => {
  const unexpectedRequests: string[] = []
  const pageErrors: string[] = []
  page.on('request', request => { if (request.url().includes('/api/') || !request.url().startsWith('http://127.0.0.1:5173')) unexpectedRequests.push(request.url()) })
  page.on('pageerror', error => pageErrors.push(error.message))
  await page.goto('/?demo=1')
  await page.evaluate(() => document.fonts.ready)
  await expect(page.getByRole('heading', { name: '研究综述', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '研究过程' })).toHaveAttribute('aria-expanded', 'false')
  await page.screenshot({ path: '../tmp/b1gone-completed-desktop.png' })
  await page.getByRole('button', { name: '关闭研究文献' }).click()
  const before = await page.locator('.workspace').boundingBox()
  await page.getByRole('button', { name: '研究文献 · 15' }).click()
  const after = await page.locator('.workspace').boundingBox()
  expect(after!.width).toBeLessThan(before!.width)
  await page.getByRole('button', { name: '查看引用文献 4' }).click()
  await expect(page.locator('[data-paper-id="paper-4"]')).toHaveClass(/paper-highlighted/)
  await page.locator('[data-paper-id="paper-4"]').getByRole('button', { name: '摘要', exact: true }).click()
  await expect(page.locator('#abstract-paper-4')).toBeVisible()
  await page.locator('[data-paper-id="paper-4"]').getByRole('button', { name: '原文', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '论文原文' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '论文原文' })).not.toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出综述' }).click()
  expect((await download).suggestedFilename()).toMatch(/B1GONE-研究综述.*\.md$/)
  expect(unexpectedRequests).toEqual([])
  expect(pageErrors).toEqual([])
})

